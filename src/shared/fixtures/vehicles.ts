/** Contagens de estoque público por loja (recalculável). */
export function computeStorePublicCounts(vehicles: VehicleListing[]): Record<string, number> {
  const counts: Record<string, number> = {};

  for (const vehicle of vehicles) {
    counts[vehicle.store.id] = (counts[vehicle.store.id] ?? 0) + 1;
  }

  return counts;
}
